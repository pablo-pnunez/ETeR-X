# -*- coding: utf-8 -*-
"""
Retrains USEM2ITM/BERT2ITM on Amazon using the correct post-fix dataset cache
(pos_tagging_fix=true, the same one used by BOW2ITM/ETeR-X and
knn_bow_baseline.py), instead of a pre-fix cache generated by an independent
run of the same pipeline (with slightly different TEST sizes, e.g.
19960/23435 rows vs. 20696/25160 in the correct cache -- the text
preprocessing has some non-deterministic step across separate runs of the
same pipeline).

Unlike run_one_retrain_amazon_fix.py, here the dataset_config is entirely NEW
(no USEM2ITM/BERT2ITM was ever trained with this cache), so there is no
early-stopping curve (dev/log.csv) to reuse: the dev=True phase must be run
first (to obtain the optimal number of epochs) and then dev=False (final
training), reusing the SAME hyperparameters already selected back then
(same learning_rate/batch_size/model_version as the old checkpoint, only
dataset_config changes).

Already includes the duplicate-reviewId fix (drop_duplicates in
__create_tfdata__ of USEM2ITM/BERT2ITM), permanently applied in the code.

Usage:
    python run_one_retrain_amazon_correct_cache.py --model BERT2ITM --subset fashion
"""
import argparse
import json
import os
import sys

parser = argparse.ArgumentParser()
parser.add_argument('--model', required=True, choices=['USEM2ITM', 'BERT2ITM'])
parser.add_argument('--subset', required=True, choices=['fashion', 'digital_music'])
parser.add_argument('--phase', required=True, choices=['dev', 'final'],
                     help="dev and final ALWAYS in separate processes: training both "
                          "phases within the same process/model instance was found to leave the "
                          "optimizer's learning rate unreset between phases for USEM2ITM (linear_decay has "
                          "no floor, it ends up negative). The original pipeline (FinalTrain.py) always "
                          "ran dev and final in independent processes -- this replicates that pattern.")
parser.add_argument('--gpu', type=int, default=0)
args = parser.parse_args()

os.environ["CUDA_VISIBLE_DEVICES"] = str(args.gpu)
os.environ["KERAS_BACKEND"] = "tensorflow"

from src.datasets.text_datasets.AmazonDataset import AmazonDataset
from src.models.text_models.USEM2ITM import USEM2ITM
from src.models.text_models.BERT2ITM import BERT2ITM

MODEL_CLASSES = {"USEM2ITM": USEM2ITM, "BERT2ITM": BERT2ITM}
MIXED_PRECISION = {"USEM2ITM": True, "BERT2ITM": True}

# Hyperparameters already selected by the original grid search for each
# combo (see the cfg.json of the corresponding "final" checkpoint under
# models/{model}/amazon/{subset}/) -- only reused here, the search itself
# is not repeated.
MODEL_CFGS = {
    ("USEM2ITM", "fashion"): {"model_version": "0", "learning_rate": 1e-05, "final_learning_rate": 1e-07,
                               "epochs": 1000, "batch_size": 2048, "seed": 100,
                               "early_st_first_epoch": 0, "early_st_monitor": "val_loss",
                               "early_st_monitor_mode": "min", "early_st_patience": 50},
    ("USEM2ITM", "digital_music"): {"model_version": "0", "learning_rate": 1e-05, "final_learning_rate": 1e-07,
                                     "epochs": 1000, "batch_size": 2048, "seed": 100,
                                     "early_st_first_epoch": 0, "early_st_monitor": "val_loss",
                                     "early_st_monitor_mode": "min", "early_st_patience": 50},
    ("BERT2ITM", "fashion"): {"model_version": "0", "learning_rate": 0.001, "final_learning_rate": 1e-05,
                               "epochs": 1000, "batch_size": 512, "seed": 100,
                               "early_st_first_epoch": 0, "early_st_monitor": "val_loss",
                               "early_st_monitor_mode": "min", "early_st_patience": 50},
    ("BERT2ITM", "digital_music"): {"model_version": "0", "learning_rate": 1e-05, "final_learning_rate": 1e-07,
                                     "epochs": 1000, "batch_size": 512, "seed": 100,
                                     "early_st_first_epoch": 0, "early_st_monitor": "val_loss",
                                     "early_st_monitor_mode": "min", "early_st_patience": 50},
}

# Correct post-fix dts_cfg (identical to the one BOW2ITM uses), taken from
# models/BOW2ITM/amazon/{subset}/*/cfg.json with pos_tagging_fix=true.
BOW_CFG_PATHS = {
    "fashion": "models/BOW2ITM/amazon/fashion/ad184096499d86322cc6c54158ae4fce/cfg.json",
    "digital_music": "models/BOW2ITM/amazon/digital_music/0cca0ace1e36d81d6a5151cfec7ab231/cfg.json",
}

with open(BOW_CFG_PATHS[args.subset]) as f:
    dts_cfg = json.load(f)["dataset_config"]
assert dts_cfg.get("pos_tagging_fix") is True, "dts_cfg does not have pos_tagging_fix=true, something is wrong"

mdl_cfg_model = MODEL_CFGS[(args.model, args.subset)]
mdl_cfg = {"model": mdl_cfg_model, "session": {"gpu": args.gpu, "mixed_precision": MIXED_PRECISION[args.model], "in_md5": False}}

text_dataset = AmazonDataset(dts_cfg)
model = MODEL_CLASSES[args.model](mdl_cfg, text_dataset)

print(f"MODEL_PATH: {model.MODEL_PATH}")
print(f"TEST size: {len(text_dataset.DATA['TEST'])}")

dev_checkpoint = model.MODEL_PATH + "dev/checkpoint"
final_checkpoint = model.MODEL_PATH + "checkpoint"

if args.phase == "dev":
    if os.path.exists(dev_checkpoint):
        print("Dev already trained for this exact config -- nothing to do.")
        sys.exit(0)
    print("Training dev (early stopping) to obtain the number of epochs...")
    model.train(dev=True, save_model=True)
    print(f"DEV_DONE {args.model}/amazon/{args.subset} -> {model.MODEL_PATH}")

else:  # final
    if os.path.exists(final_checkpoint):
        print("A final checkpoint already exists for this exact config -- nothing to do.")
        sys.exit(0)
    if not os.path.exists(dev_checkpoint):
        print(f"FATAL: no dev/checkpoint at {model.MODEL_PATH} -- run --phase dev first")
        sys.exit(1)
    print("Final training (full train+dev, new process -> fresh optimizer)...")
    model.train(dev=False, save_model=True)

    print("Evaluating (per-review + per-user)...")
    model.evaluate(test=True, user_info=True)

    print(f"DONE {args.model}/amazon/{args.subset} -> {model.MODEL_PATH}")
